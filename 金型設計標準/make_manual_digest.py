def sm(t): return Paragraph(t, S['sm'])
def bullets(items): return [Paragraph('・' + i, S['b']) for i in items]


def tbl(rows, widths, head=True, bg=None, small=False):
    t = Table(rows, colWidths=widths, repeatRows=1 if head else 0)
    st = [('GRID', (0, 0), (-1, -1), 0.5, MGRAY), ('VALIGN', (0, 0), (-1, -1), 'TOP'),
          ('TOPPADDING', (0, 0), (-1, -1), 3.5 if small else 4),
          ('BOTTOMPADDING', (0, 0), (-1, -1), 3.5 if small else 4),
          ('LEFTPADDING', (0, 0), (-1, -1), 5)]
    if head:
        st.append(('BACKGROUND', (0, 0), (-1, 0), BLUE))
    if bg:
        st.append(('BACKGROUND', (0, 1), (-1, -1), bg))
    t.setStyle(TableStyle(st))
    return t


def box(text, bg=AMBER, border='#e0c66b'):
    t = Table([[Paragraph(text, S['b'])]], colWidths=[W])
    t.setStyle(TableStyle([('BACKGROUND', (0, 0), (-1, -1), bg),
                           ('BOX', (0, 0), (-1, -1), 0.8, colors.HexColor(border)),
                           ('TOPPADDING', (0, 0), (-1, -1), 6), ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
                           ('LEFTPADDING', (0, 0), (-1, -1), 8), ('RIGHTPADDING', (0, 0), (-1, -1), 8)]))
    return t


# 症状→確認→対策の3列表。相関図をたどる順に並べる
def diag(title, rows):
    """rows = [(症状/条件, 確認すること, 対策), ...]"""
    data = [[Paragraph('<b>症状・条件</b>', S['hw']), Paragraph('<b>確認すること</b>', S['hw']),
             Paragraph('<b>対策</b>', S['hw'])]]
    for a, b, c in rows:
        data.append([sm(a), sm(b), sm(c)])
    return KeepTogether([h2(title), tbl(data, [46 * mm, 62 * mm, 80 * mm], small=True)])


