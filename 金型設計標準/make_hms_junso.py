def build(out):
    wb = Workbook()

    ws = wb.active
    ws.title = '00_はじめに'
    ws.column_dimensions['A'].width = 24
    ws.column_dimensions['B'].width = 108
    ws['A1'] = 'HMS 金型設計標準【順送編】'
    ws['A1'].font = Font(name='Meiryo UI', size=16, bold=True, color=NAVY)
    ws['A2'] = '橋本工業株式会社　技術部　／　骨格版（内容記入用）'
    ws['A2'].font = Font(name='Meiryo UI', size=9, color='FF666666')
    r = 4
    for title, body in NOTE_SHEET:
        ws.cell(r, 1, title).font = Font(name='Meiryo UI', size=10, bold=True, color=NAVY)
        ws.cell(r, 1).alignment = WRAP
        c = ws.cell(r, 2, body)
        c.alignment, c.font = WRAP, Font(name='Meiryo UI', size=9)
        ws.row_dimensions[r].height = 46
        r += 1

    ws = wb.create_sheet('01_順送編')
    headers = ['章', 'No', '項目', '規定内容（案）', '参考値・他社水準',
               '過去トラとの対応', '相関図', '分類', '採否', '備考']
    widths = [16, 7, 24, 66, 34, 34, 8, 8, 8, 22]
    for i, (h, w) in enumerate(zip(headers, widths), 1):
        ws.cell(1, i, h)
        ws.column_dimensions[get_column_letter(i)].width = w
    style_header(ws, len(headers))
    ws.freeze_panes = 'A2'

    cat_fill = {'品質': PINK, '保守': LGRAY, '安全': AMBER, '生産性': GREEN}
    prev = None
    r = 2
    for chap, no, name, rule, ref, tora, zu, cat in ITEMS:
        rule_txt = rule.replace('<strong>', '').replace('</strong>', '')
        vals = [chap if chap != prev else '', no, name, rule_txt, ref, tora, zu, cat, '', '']
        for i, v in enumerate(vals, 1):
            c = ws.cell(r, i, v)
            c.alignment, c.border = WRAP, BOX
            c.font = Font(name='Meiryo UI', size=9, bold=(i == 1 and chap != prev))
        if cat in cat_fill:
            ws.cell(r, 8).fill = PatternFill('solid', fgColor=cat_fill[cat])
        if tora:
            ws.cell(r, 6).fill = PatternFill('solid', fgColor=PINK)
            ws.cell(r, 6).font = Font(name='Meiryo UI', size=9, bold=True, color='FF9C0006')
        ws.row_dimensions[r].height = max(30, min(110, len(rule_txt) * 0.5))
        prev = chap
        r += 1

    ws2 = wb.create_sheet('02_集計')
    for col, w in zip('ABC', (24, 12, 56)):
        ws2.column_dimensions[col].width = w
    ws2['A1'] = '章別の項目数'
    ws2['A1'].font = Font(name='Meiryo UI', size=11, bold=True, color=NAVY)
    chaps = []
    for x in ITEMS:
        if x[0] not in chaps:
            chaps.append(x[0])
    r = 2
    for ch in chaps:
        n = sum(1 for x in ITEMS if x[0] == ch)
        nt = sum(1 for x in ITEMS if x[0] == ch and x[5])
        ws2.cell(r, 1, ch).font = Font(name='Meiryo UI', size=9)
        ws2.cell(r, 2, n).font = Font(name='Meiryo UI', size=9)
        ws2.cell(r, 3, ('うち過去トラ根拠 %d件' % nt) if nt else '').font = \
            Font(name='Meiryo UI', size=9, color='FF9C0006')
        r += 1
    ws2.cell(r, 1, '合計').font = Font(name='Meiryo UI', size=10, bold=True)
    ws2.cell(r, 2, len(ITEMS)).font = Font(name='Meiryo UI', size=10, bold=True)
    r += 2
    ws2.cell(r, 1, '分類別').font = Font(name='Meiryo UI', size=11, bold=True, color=NAVY)
    r += 1
    for cat in ['品質', '保守', '安全', '生産性', '—']:
        n = sum(1 for x in ITEMS if x[7] == cat)
        if n:
            ws2.cell(r, 1, cat).font = Font(name='Meiryo UI', size=9)
            ws2.cell(r, 2, n).font = Font(name='Meiryo UI', size=9)
            r += 1

    wb.save(out)
    print('作成しました:', out)
    print('  項目数:', len(ITEMS),
          '／ 過去トラ紐づけ:', sum(1 for x in ITEMS if x[5]),
          '／ 相関図紐づけ:', sum(1 for x in ITEMS if x[6]))


if __name__ == '__main__':
    build(sys.argv[1] if len(sys.argv) > 1 else 'HMS金型設計標準_順送編_骨格.xlsx')
