def build(src, dst):
    wb = openpyxl.load_workbook(src)
    ws = wb['01_順送編']

    ncol = ws.max_column
    fig_col = ncol + 1
    c = ws.cell(1, fig_col, '参考図（他社資料）')
    c.font = Font(name='Meiryo UI', size=9, bold=True, color='FFFFFFFF')
    c.fill = PatternFill('solid', fgColor='FF2E5C9A')
    c.alignment = Alignment(wrap_text=True, vertical='center', horizontal='center')
    c.border = BOX
    ws.column_dimensions[get_column_letter(fig_col)].width = 32

    idx = {}
    for r in range(2, ws.max_row + 1):
        no = ws.cell(r, 2).value
        if no:
            idx[str(no).strip()] = r

    n_fig = n_rule = 0
    for no, fig in FIGS.items():
        r = idx.get(no)
        if r:
            cc = ws.cell(r, fig_col, fig)
            cc.alignment, cc.font, cc.border = WRAP, F9, BOX
            n_fig += 1

    for no, txt in RULES.items():
        r = idx.get(no)
        if not r:
            continue
        t = txt.replace('<b>', '').replace('</b>', '')
        cc = ws.cell(r, 4, t)
        cc.alignment, cc.font, cc.fill = WRAP, F9, YELLOW
        ws.row_dimensions[r].height = max(34, min(170, len(t) * 0.5))
        n_rule += 1

    # 「不要」の行を灰色に
    for r in range(2, ws.max_row + 1):
        if str(ws.cell(r, 9).value or '').strip() in ('不要', '対象外'):
            for col in range(1, fig_col + 1):
                ws.cell(r, col).fill = GRAY

    # 第12章
    r = ws.max_row + 1
    prev = None
    for chap, no, name, rule, ref, tora, zu, cat in NEW_ITEMS:
        vals = [chap if chap != prev else '', no, name, rule, ref, tora, zu, cat, '', '']
        for i, v in enumerate(vals, 1):
            cc = ws.cell(r, i, v)
            cc.alignment, cc.border, cc.fill = WRAP, BOX, NEWROW
            cc.font = Font(name='Meiryo UI', size=9, bold=(i == 1 and chap != prev))
        cc = ws.cell(r, fig_col, '—')
        cc.border, cc.fill = BOX, NEWROW
        if tora:
            ws.cell(r, 6).font = Font(name='Meiryo UI', size=9, bold=True, color='FF9C0006')
        ws.row_dimensions[r].height = max(36, min(140, len(rule) * 0.5))
        prev = chap
        r += 1

    # 変更履歴
    if '03_変更履歴' in wb.sheetnames:
        del wb['03_変更履歴']
    ws2 = wb.create_sheet('03_変更履歴')
    for col, w in zip('ABC', (14, 24, 96)):
        ws2.column_dimensions[col].width = w
    for i, h in enumerate(('日付', '項目', '内容'), 1):
        cc = ws2.cell(1, i, h)
        cc.font = Font(name='Meiryo UI', size=9, bold=True, color='FFFFFFFF')
        cc.fill = PatternFill('solid', fgColor='FF2E5C9A')
    rows = [
        ('2026-07-22', '全体', '技術部が修正・コメントを記入（76箇所）'),
        ('2026-07-22', '参考図 列を追加', '他社資料のスライド番号を67項目に記載。'
                                      '_図面参考/順送_スライド に100枚を画像化済み'),
        ('2026-07-22', '「わからない」15項目', '規定内容に説明を補い、'
                                          '図を見なくても意味が通るようにした'),
        ('2026-07-22', '3-1 送り方向', 'A1号機＝右送り／A2号機＝左送り の自社実態を反映'),
        ('2026-07-22', '9-7 締付けボルト', '全数トルクレンチは非現実的との指摘を受け、'
                                       '重要部位のみトルク管理＋定期増し締めの運用に変更'),
        ('2026-07-22', '第12章を新設', 'BUR狙い値・CUT-BE設計値管理表から'
                                    '計算方法・考え方を8項目として織り込み（単発編第9章と同一）'),
        ('2026-07-22', '要検討', '2-2金型の表示・2-6ダイハイト・4-1上型 は「単発編に合わせる」'
                              'とのコメントあり。共通編への統合時に整理する'),
        ('2026-07-22', '未回答', '1-5 プレス別SPM表 → 他社資料に一覧なし。'
                              '自社のプレス能力から設定が必要'),
    ]
    for r2, (d, k, v) in enumerate(rows, 2):
        for c2, val in enumerate((d, k, v), 1):
            cc = ws2.cell(r2, c2, val)
            cc.font, cc.alignment = F9, WRAP

    wb.save(dst)
    print('作成しました:', dst)
    print('  参考図: %d項目 ／ 規定を補足: %d項目 ／ 第12章: %d項目'
          % (n_fig, n_rule, len(NEW_ITEMS)))


if __name__ == '__main__':
    build(sys.argv[1], sys.argv[2])
