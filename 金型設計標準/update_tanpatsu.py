# ── 規定内容を一部だけ差し替えるもの ─────────────────────
PARTIAL = {
    '7-10': '規格品を使用する。露出したコイルスプリングには安全カバーを取付けること。',
    '7-11': '金型の部品締付に使用する全てのボルトは、締付トルク表のトルク以上で締付ける。'
            '※過去に固定ボルトの緩みでカット刃が欠け、バリ・変形が発生した実績がある。',
}


def build(src, dst):
    wb = openpyxl.load_workbook(src)
    ws = wb['01_単発編']

    # No → 行番号
    idx = {}
    for r in range(2, ws.max_row + 1):
        no = ws.cell(r, 2).value
        if no:
            idx[str(no).strip()] = r

    n_rule = n_dec = 0

    for no, txt in list(RULES.items()) + list(PARTIAL.items()):
        r = idx.get(no)
        if not r:
            continue
        c = ws.cell(r, 4, txt)
        c.alignment, c.font, c.fill = WRAP, F9, YELLOW
        ws.row_dimensions[r].height = max(34, min(150, len(txt) * 0.52))
        n_rule += 1

    for no, (dec, why) in DECISIONS.items():
        r = idx.get(no)
        if not r:
            continue
        c = ws.cell(r, 8, dec)
        c.alignment, c.font = WRAP, F9B
        if dec == '対象外':
            for col in range(1, 11):
                ws.cell(r, col).fill = GRAY
        prev = str(ws.cell(r, 9).value or '').strip()
        note = (prev + '　／　' if prev else '') + why
        c2 = ws.cell(r, 9, note)
        c2.alignment, c2.font = WRAP, F9
        n_dec += 1

    # 変更履歴シート
    if '03_変更履歴' in wb.sheetnames:
        del wb['03_変更履歴']
    ws2 = wb.create_sheet('03_変更履歴')
    for col, w in zip('ABC', (14, 22, 96)):
        ws2.column_dimensions[col].width = w
    ws2['A1'] = '日付'
    ws2['B1'] = '項目'
    ws2['C1'] = '内容'
    for c in range(1, 4):
        ws2.cell(1, c).font = Font(name='Meiryo UI', size=9, bold=True, color='FFFFFFFF')
        ws2.cell(1, c).fill = PatternFill('solid', fgColor='FF2E5C9A')
    rows = [
        ('2026-07-21', '全体', '技術部が備考・採否を記入（19項目）'),
        ('2026-07-22', '全体', '記入内容への回答を規定内容へ反映。更新箇所は黄色、対象外は灰色'),
        ('2026-07-22', '前提の確認', '売型はせず全て社内生産 → 客先提出用の書類項目は対象外にできる'),
        ('2026-07-22', '前提の確認', 'オートクランプなし → U溝長さ30mm以上／クランプ部厚み30〜50mm に確定'),
        ('2026-07-22', '3-4 上型', 'オートクランプ無しの前提で数値を確定'),
        ('2026-07-22', '4-9 アテピン', '板厚別の高さ表を追記（T≦3.2→3.5／3.2<T→H≒T）'),
        ('2026-07-22', '7-6 抜きダイ', '他社規定の数値を追記（250mm角・座ぐり+3mm・20kg・C1以上ほか）'),
        ('2026-07-22', '7-7 抜きパンチ', '他社規定の数値を追記（板厚+1mm・刃長10mm・タップM6/M8ほか）'),
        ('2026-07-22', '7-1 入れ子', '「減り方が違うものを一体にしない」と言い換え、②③を平易な表現に'),
        ('2026-07-22', '7-10・7-11', '「不要」から「採用」へ変更を提案（安全項目／過去トラ実績あり）'),
        ('2026-07-22', '未定事項', '4-3 テーパ角度・5-1 払出し角度・1-4 歩留り目標 は実測・実績待ち'),
    ]
    for r, (d, k, v) in enumerate(rows, 2):
        for c, val in enumerate((d, k, v), 1):
            cell = ws2.cell(r, c, val)
            cell.font, cell.alignment = F9, WRAP

    wb.save(dst)
    print('作成しました:', dst)
    print('  規定内容を更新: %d項目 ／ 採否を記入: %d項目' % (n_rule, n_dec))


if __name__ == '__main__':
    build(sys.argv[1], sys.argv[2])
